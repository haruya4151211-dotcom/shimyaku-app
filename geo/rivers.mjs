// 河川の流路を生成する： npm run geo（geo/build.mjs の後に実行）
// 入力：geo/.cache の Natural Earth 10m 河川・湖中心線（RIVERS_URL から取得）、src/data/atlas/geography.js の GEO_RIVERS
// 出力：src/data/generated/riverPaths.js（川の名前 → SVG パス。座標は mapProjection.js と同じ viewBox）
// 流路は Douglas–Peucker 法で間引き（RIVER_TOLERANCE）、0.1単位に丸めて相対座標で書く。
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GEO_RIVERS } from "../src/data/atlas/geography.js";
import { lonLatToXY } from "../src/data/mapProjection.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const RIVERS_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_rivers_lake_centerlines.geojson";
const SOURCE = path.join(HERE, ".cache", "ne_10m_rivers_lake_centerlines.geojson");
const OUT = path.join(HERE, "..", "src", "data", "generated", "riverPaths.js");
const RIVER_TOLERANCE = 0.12; // 間引きの許容誤差（viewBox 単位。1 ≒ 経度0.35°）

if (!fs.existsSync(SOURCE)) { console.error(`Natural Earth の河川データがありません。次のURLから ${SOURCE} へ保存してください:\n${RIVERS_URL}`); process.exit(1); }
const features = JSON.parse(fs.readFileSync(SOURCE, "utf8")).features;
const nameOf = (p) => [p.name, p.name_alt, p.name_en].filter(Boolean);
const inBox = (line, b) => !b || line.some(([x, y]) => x >= b[0] && x <= b[2] && y >= b[1] && y <= b[3]);
const perp = ([x, y], [ax, ay], [bx, by]) => {
  const dx = bx - ax, dy = by - ay, L = dx * dx + dy * dy;
  const t = L ? Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / L)) : 0;
  return Math.hypot(x - ax - t * dx, y - ay - t * dy);
};
const simplify = (pts, tol) => {
  if (pts.length <= 2) return pts;
  let idx = 0, max = 0;
  for (let i = 1; i < pts.length - 1; i++) { const d = perp(pts[i], pts[0], pts[pts.length - 1]); if (d > max) { max = d; idx = i; } }
  if (max <= tol) return [pts[0], pts[pts.length - 1]];
  return [...simplify(pts.slice(0, idx + 1), tol).slice(0, -1), ...simplify(pts.slice(idx), tol)];
};
const fmt = (v) => (Math.round(v * 10) / 10).toString().replace(/^(-?)0\./, "$1.");

const out = {}, problems = [];
for (const r of GEO_RIVERS) {
  const lines = [];
  for (const ft of features) {
    if (!nameOf(ft.properties).some((n) => r.ne.includes(n))) continue;
    const g = ft.geometry;
    for (const line of g.type === "LineString" ? [g.coordinates] : g.coordinates) if (inBox(line, r.bbox)) lines.push(line);
  }
  if (!lines.length) { problems.push(`${r.name}: Natural Earth に該当する流路がない（${r.ne.join(" / ")}）`); continue; }
  let d = "";
  for (const line of lines) {
    const pts = simplify(line.map(([lon, lat]) => lonLatToXY(lon, lat)), RIVER_TOLERANCE);
    if (pts.length < 2) continue;
    d += `M${fmt(pts[0][0])} ${fmt(pts[0][1])}` + pts.slice(1).map((p, i) => `l${fmt(p[0] - pts[i][0])} ${fmt(p[1] - pts[i][1])}`).join("");
  }
  out[r.name] = d.replace(/ -/g, "-");
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
const js = `// AUTO-GENERATED by geo/rivers.mjs — 手編集しないこと（定義は src/data/atlas/geography.js の GEO_RIVERS）
// 出典：Natural Earth 10m rivers and lake centerlines（パブリックドメイン）を mapProjection.js と同じ投影で viewBox 座標に変換し、間引いたもの
/* eslint-disable */
export const RIVER_PATHS = ${JSON.stringify(out)};
`;
fs.writeFileSync(OUT, js);
console.log(`${Object.keys(out).length} rivers, ${(js.length / 1024).toFixed(0)} KB`);
